namespace Mafesoft.Localization.Resx
{
    using System;
    using System.Collections;
    using System.Collections.Generic;
    using System.Globalization;
    using System.Resources;
    using System.Threading;
    using System.Threading.Tasks;

    /// <summary>
    /// Loads the vocabularies from existing <c>.resx</c> files through their <see cref="ResourceManager"/>, so an
    /// application can adopt Mafesoft.Localization (XAML markup, runtime culture switch, missing-key reporting) without
    /// converting its resources.
    /// </summary>
    /// <remarks>
    /// The vocabulary of a culture has the strings of the culture and, for the keys it does not have, of its parent
    /// cultures down to the neutral resources (<c>Strings.it-IT.resx</c>, <c>Strings.it.resx</c>, <c>Strings.resx</c>),
    /// as <see cref="ResourceManager.GetString(string, CultureInfo)"/> does. Resources that are not strings (images,
    /// streams) are skipped. The <c>.resx</c> files are compiled into the application: <see cref="SaveAsync"/> and
    /// <see cref="AddOrUpdateTermAsync"/> do nothing.
    /// </remarks>
    public sealed class ResxVocabularyServiceProvider : IVocabularyServiceProvider
    {
        /// <summary>
        /// Creates the provider for the resources of a <see cref="ResourceManager"/>, for example
        /// <c>Strings.ResourceManager</c> of the class generated for <c>Strings.resx</c>.
        /// </summary>
        /// <param name="resourceManager">The resource manager.</param>
        public ResxVocabularyServiceProvider(ResourceManager resourceManager)
        {
            ResourceManager = resourceManager ?? throw new ArgumentNullException(nameof(resourceManager));
        }

        /// <summary>
        /// Creates the provider for the resources named after a type, for example <c>typeof(Strings)</c> for
        /// <c>Strings.resx</c> (the class generated by the resx designer, or any class with the same full name).
        /// </summary>
        /// <param name="resourceSource">The type whose full name and assembly locate the resources.</param>
        public ResxVocabularyServiceProvider(Type resourceSource)
            : this(new ResourceManager(resourceSource ?? throw new ArgumentNullException(nameof(resourceSource))))
        {
        }

        /// <summary>
        /// The resource manager that reads the <c>.resx</c> files.
        /// </summary>
        public ResourceManager ResourceManager { get; }

        /// <inheritdoc />
        public Task InitializeAsync(CancellationToken cancellationToken = default) => Task.CompletedTask;

        /// <summary>
        /// Loads the strings of the culture and of its parent cultures (the culture wins).
        /// </summary>
        public Task<IVocabulary> LoadVocabularyAsync(CultureInfo cultureInfo, CancellationToken cancellationToken = default)
        {
            if (cultureInfo is null) throw new ArgumentNullException(nameof(cultureInfo));
            cancellationToken.ThrowIfCancellationRequested();

            // From the neutral resources up to the culture, so the most specific value is written last.
            var chain = new Stack<CultureInfo>();
            for (var culture = cultureInfo; ; culture = culture.Parent)
            {
                chain.Push(culture);
                if (culture.Name.Length == 0)
                {
                    break;
                }
            }

            var vocabulary = new Vocabulary();
            foreach (var culture in chain)
            {
                // tryParents: false, the parents are walked here; createIfNotExists: true, load the satellite assembly.
                ResourceSet? set;
                try
                {
                    set = ResourceManager.GetResourceSet(culture, createIfNotExists: true, tryParents: false);
                }
                catch (Exception ex) when (ex is MissingManifestResourceException || ex is MissingSatelliteAssemblyException)
                {
                    // No resources for this culture (or no neutral resources): the other cultures of the chain still count.
                    continue;
                }

                if (set is null)
                {
                    continue;
                }

                foreach (DictionaryEntry entry in set)
                {
                    if (entry.Key is string key && entry.Value is string value)
                    {
                        vocabulary[key] = value;
                    }
                }
            }

            return Task.FromResult<IVocabulary>(vocabulary);
        }

        /// <summary>
        /// Does nothing: the <c>.resx</c> files are compiled into the application.
        /// </summary>
        public Task SaveAsync(IVocabulary vocabulary, CancellationToken cancellationToken = default) => Task.CompletedTask;

        /// <summary>
        /// Does nothing: the <c>.resx</c> files are compiled into the application. Use
        /// <see cref="LocalizationManager.MissingTerm"/> or <see cref="LocalizationManager.Logger"/> to see the missing keys.
        /// </summary>
        public Task AddOrUpdateTermAsync(IVocabulary vocabulary, string key, string? defaultValue = null, CancellationToken cancellationToken = default) => Task.CompletedTask;
    }
}
